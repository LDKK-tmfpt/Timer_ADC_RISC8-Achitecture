#!/usr/bin/env python3
"""Assembler for the user's pipelined 8-bit RISC core (core8risc).

usage:  python3 asm/asm.py asm/prog.asm rtl/imem_soc8risc.v

Instruction word (16 bit):  [15:12] op  [11:9] rd  [8:6] rs1  [5:3] rs2  [7:0] imm8
  0 NOP
  1 ADD  rd, rs1, rs2     (sets Z,C)     6 SHL rd, rs1   (sets Z,C)
  2 SUB  rd, rs1, rs2     (sets Z,C)     7 SHR rd, rs1   (sets Z,C)
  3 AND  rd, rs1, rs2     (sets Z,C)     8 LDI rd, imm   (no flags)
  4 OR   rd, rs1, rs2     (sets Z,C)     9 ADDI rd, imm  rd = rd + imm (sets Z,C)
  5 XOR  rd, rs1, rs2     (sets Z,C)     A LD  rd, rs1   rd = mem[rs1]
                                         B ST  rd, rs1   mem[rs1] = rd
  C JMP label   D BEQZ label (branch if Z=1)   E BNEZ label (branch if Z=0)   F HALT
Branches test the Z flag of the last flag-setting instruction.
"""
import re
import sys

OP = dict(NOP=0, ADD=1, SUB=2, AND=3, OR=4, XOR=5, SHL=6, SHR=7, LDI=8,
          ADDI=9, LD=10, ST=11, JMP=12, BEQZ=13, BNEZ=14, HALT=15)
R3 = {"ADD", "SUB", "AND", "OR", "XOR"}
R2 = {"SHL", "SHR", "LD", "ST"}
RI = {"LDI", "ADDI"}
BR = {"JMP", "BEQZ", "BNEZ"}


def reg(tok):
    m = re.fullmatch(r"[rR]([0-7])", tok.strip())
    if not m:
        raise ValueError("bad register '%s'" % tok)
    return int(m.group(1))


def assemble(src):
    items, labels, pc = [], {}, 0
    for raw in src.splitlines():
        line = raw.split(";")[0].strip()
        while ":" in line:
            lab, line = line.split(":", 1)
            labels[lab.strip()] = pc
            line = line.strip()
        if line:
            items.append((pc, line))
            pc += 1

    def val(tok):
        tok = tok.strip()
        return labels[tok] if tok in labels else int(tok, 0)

    words = []
    for pc, line in items:
        parts = line.split(None, 1)
        mn = parts[0].upper()
        args = [a.strip() for a in parts[1].split(",")] if len(parts) > 1 else []
        if mn not in OP:
            raise ValueError("unknown mnemonic '%s' in: %s" % (mn, line))
        w = OP[mn] << 12
        if mn in R3:
            w |= reg(args[0]) << 9 | reg(args[1]) << 6 | reg(args[2]) << 3
        elif mn in R2:                       # SHL/SHR rd,rs1  LD rd,rs1  ST rd,rs1
            w |= reg(args[0]) << 9 | reg(args[1]) << 6
        elif mn in RI:
            imm = val(args[1])
            assert 0 <= imm <= 255, line
            w |= reg(args[0]) << 9 | imm
        elif mn in BR:
            w |= val(args[0])
        words.append((pc, w, line))
    return words


def write_imem(words, path):
    with open(path, "w") as f:
        f.write("`timescale 1ns / 1ps\n")
        f.write("// AUTO-GENERATED by asm/asm.py from asm/prog.asm - do not edit\n")
        f.write("// Same ports as the original imem8risc.\n")
        f.write("module imem_soc8risc (\n    input  wire [7:0]  addr,\n"
                "    output reg  [15:0] instr\n);\n")
        f.write("    always @(*) begin\n        case (addr)\n")
        for pc, w, line in words:
            f.write("            8'h%02X: instr = 16'h%04X;   // %s\n" % (pc, w, line))
        f.write("            default: instr = 16'hF000;   // HALT\n")
        f.write("        endcase\n    end\nendmodule\n")


if __name__ == "__main__":
    words = assemble(open(sys.argv[1]).read())
    write_imem(words, sys.argv[2])
    for pc, w, line in words:
        print("%02X  %04X  %s" % (pc, w, line))
    print("-> %d instructions written to %s" % (len(words), sys.argv[2]))
